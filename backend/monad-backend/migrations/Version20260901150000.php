 * in `monad_knowledge/lab/placements.py`, which reads PostGIS; this backend has no
 * view of PostGIS and must not grow a second implementation of that rule. On
 * `fiit-ground-0` the two reading rooms have marker cards 1.2 m apart through
 * concrete while the openings are at x = 1.24 m and x = 10.60 m, so the tempting
 * leg is the impossible one, and an unwalkable leg still renders as a short line
 * on a plan. One implementation, or the bug comes back on one side only.
 *
 * `realised_steps` records what a given enrollment was actually asked to walk. It
 * stores the SEQUENCE and not a random seed, because a seed only reproduces an
 * order against a frozen generator, and that generator is not frozen: it gained
 * door awareness on 2026-09-01 and will change again.
 *
 * 3. `quest_enrollments.points_awarded` / `awarded_at`
