 * received.
 *
 * Frozen at completion rather than derived, because `quests.points` is mutable and
 * a derived total silently rewrites history the first time a quest is re-valued.
 *
 * THE BACKFILL BELOW IS A RECONSTRUCTION, NOT A RECORD. It stamps every already
 * completed enrollment with the quest's CURRENT value, because nothing ever
 * recorded what those walkers were actually promised. It is the best available
